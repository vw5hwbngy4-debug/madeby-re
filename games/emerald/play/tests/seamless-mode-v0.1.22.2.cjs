assert(!index.includes('href="./dex.html"'), 'DEX control must not navigate to dex.html');
assert(index.includes('mode-switch-v0.1.22.2.js'), 'mode switch JS loaded');
assert(index.includes('strategy-pokedex-v0.1.22.2.css'), 'DEX scoped CSS loaded');
